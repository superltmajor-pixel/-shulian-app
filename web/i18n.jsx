function normalizeUiLanguage(value) {
  return value === 'en' ? 'en' : UI_LANGUAGE_DEFAULT;
}

function currentUiLanguage() {
  return normalizeUiLanguage(document.documentElement.dataset.uiLanguage);
}

function uiT(source, variables = {}) {
  const template = currentUiLanguage() === 'en' ? (UI_EN[source] || source) : source;
  return Object.entries(variables).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    String(template),
  );
}

function useUiLanguage() {
  const [language, setLanguageState] = React.useState(currentUiLanguage);
  React.useEffect(() => {
    const sync = event => setLanguageState(normalizeUiLanguage(event?.detail?.language || currentUiLanguage()));
    window.addEventListener(UI_LANGUAGE_EVENT, sync);
    return () => window.removeEventListener(UI_LANGUAGE_EVENT, sync);
  }, []);
  const setLanguage = React.useCallback(languageValue => {
    const languageNext = normalizeUiLanguage(languageValue);
    window.applyShulianLanguage?.(languageNext);
    return languageNext;
  }, []);
  return { language, setLanguage };
}

Object.assign(window, { normalizeUiLanguage, currentUiLanguage, uiT, useUiLanguage });
